"""The planning model: the simple, deterministic view of the factory a planner works with.

A planner can't run the full simulator inside its search, so it uses four
numbers per line, all calibrated FROM the simulator:

    seconds_per_good_board[line][product]   effective pace, including breakdowns,
                                            consumable stops and rejects
    first_pass_yield[line][product]         share of boards that pass inspection
                                            (used as the planned scrap allowance)
    changeover_s[line][from][to]            time lost when switching product
    fill_s[line]                            time for an empty line to deliver its
                                            first board (it starts empty)

Predicted timeline of one line running lots L1, L2, ... :

    t = fill
    for each lot:  t += changeover(previous product -> this product) + qty * seconds_per_good_board
                   lot completes at t

How each number is measured (see calibrate()):

  * changeover: deterministic runs (no randomness), so the number is exact.
    T(x) = time until the last board of plan x leaves the line. Then
        changeover(i -> j) = T(i N, j N) - T(i N) - (T(j N) - fill_j)
    i.e. how much longer "i then j" takes than "i" plus j's own work. This
    captures the real line-level cost: the changeover ripples down the line
    station by station, so it is not simply the sum of the station setup times.
  * fill and pace: from the same deterministic runs, pace c = (T(2N) - T(N)) / N
    and fill = T(N) - N * c.
  * seconds per good board: randomized single-product runs over several
    seeds, measured after a warm-up: elapsed time / good boards out. This is
    slower than the deterministic pace, because it includes failures and rejects.
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from smt_sim import Simulator
from smt_sim.config import make_deterministic
from smt_sim.metrics import quality_report

CALIBRATION_BOARDS = 40   # boards per product in the deterministic runs (> line WIP, so pace is steady)


@dataclass
class PlanningModel:
    lines: list[str]
    products: list[str]
    seconds_per_good_board: dict[str, dict[str, float]]
    changeover_s: dict[str, dict[str, dict[str, float]]]
    fill_s: dict[str, float]
    first_pass_yield: dict[str, dict[str, float]]

    def lot_duration_s(self, line: str, product: str, quantity: int) -> float:
        return quantity * self.seconds_per_good_board[line][product]

    def setup_s(self, line: str, previous: str | None, product: str) -> float:
        """Changeover before a lot. The first lot on a line needs none (line starts set up)."""
        return 0.0 if previous is None else self.changeover_s[line][previous][product]

    # ---- save / load -----------------------------------------------------------

    def save(self, path: str | Path) -> None:
        data = {
            "lines": self.lines,
            "products": self.products,
            "seconds_per_good_board": self.seconds_per_good_board,
            "changeover_s": self.changeover_s,
            "fill_s": self.fill_s,
            "first_pass_yield": self.first_pass_yield,
        }
        with open(path, "w", encoding="utf-8") as f:
            f.write("# Generated by scripts/calibrate_planning_model.py - do not edit by hand.\n")
            yaml.safe_dump(data, f, sort_keys=False)

    @classmethod
    def load(cls, path: str | Path) -> "PlanningModel":
        with open(path, encoding="utf-8") as f:
            data = yaml.safe_load(f)
        return cls(**data)


# ---- calibration -------------------------------------------------------------------


def time_to_finish(line_config: dict[str, Any], jobs: list[tuple[str, int]], max_s: float = 7 * 24 * 3600) -> float:
    """Run a finite plan and return the time the last board left the line."""
    cfg = dict(line_config)
    cfg["production_plan"] = {"jobs": [{"product": p, "quantity": q} for p, q in jobs]}
    cfg.pop("orders", None)
    sim = Simulator(cfg)
    total = sum(q for _, q in jobs)
    while len(sim.sink) + len(sim.rejected_boards()) < total and sim.time_s < max_s:
        sim.run(60)
    finished = sim.sink.boards() + sim.rejected_boards()
    return max(max(b.time_out_s.values()) for b in finished)


def calibrate_changeovers(line_config: dict[str, Any], products: list[str],
                          n: int = CALIBRATION_BOARDS) -> tuple[dict[str, dict[str, float]], float, dict[str, float]]:
    """Deterministic runs -> (changeover matrix, fill time, deterministic pace per product)."""
    det = make_deterministic(line_config)
    single = {p: time_to_finish(det, [(p, n)]) for p in products}
    double = {p: time_to_finish(det, [(p, 2 * n)]) for p in products}
    pace = {p: (double[p] - single[p]) / n for p in products}
    fill = {p: single[p] - n * pace[p] for p in products}

    changeover = {i: {j: 0.0 for j in products} for i in products}
    for i in products:
        for j in products:
            if i != j:
                both = time_to_finish(det, [(i, n), (j, n)])
                changeover[i][j] = both - single[i] - (single[j] - fill[j])
    # The line's fill time hardly depends on the product; use the average.
    return changeover, sum(fill.values()) / len(fill), pace


def calibrate_pace(line_config: dict[str, Any], product: str, seeds: list[int],
                   hours: float = 12.0, warmup_h: float = 1.0) -> tuple[float, float]:
    """Randomized runs -> (seconds per GOOD board, first-pass yield) for one product."""
    cfg = dict(line_config)
    cfg["production_plan"] = {"jobs": [{"product": product}]}
    cfg.pop("orders", None)
    rates, yields = [], []
    for seed in seeds:
        sim = Simulator(cfg, seed=seed)
        sim.run(warmup_h * 3600)
        before = sim.boards_completed
        sim.run((hours - warmup_h) * 3600)
        rates.append((sim.boards_completed - before) / ((hours - warmup_h) * 3600))
        yields.append(quality_report(sim).first_pass_yield)
    return 1.0 / (sum(rates) / len(rates)), sum(yields) / len(yields)


def calibrate(line_configs: dict[str, dict[str, Any]], products: list[str], seeds: list[int],
              hours: float = 12.0, deterministic_pace: bool = False) -> PlanningModel:
    """Build a PlanningModel for these lines by running the simulator.

    deterministic_pace=True uses the no-randomness pace instead of the
    randomized seconds-per-good-board (fast; used by tests).
    """
    spb, changeovers, fills, fpy = {}, {}, {}, {}
    for line, cfg in line_configs.items():
        changeovers[line], fills[line], det_pace = calibrate_changeovers(cfg, products)
        if deterministic_pace:
            spb[line] = det_pace
            fpy[line] = {p: 1.0 for p in products}
        else:
            measured = {p: calibrate_pace(cfg, p, seeds, hours) for p in products}
            spb[line] = {p: pace for p, (pace, _) in measured.items()}
            fpy[line] = {p: y for p, (_, y) in measured.items()}
    return PlanningModel(list(line_configs), list(products), spb, changeovers, fills, fpy)
